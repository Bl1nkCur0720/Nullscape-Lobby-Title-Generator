(function registerFontFaces() {
  if (typeof FontFace === 'undefined' || !document.fonts) return;

  FONT_FACE_DEFS.forEach(function (def) {
    try {
      const face = new FontFace(def.family, `url("${def.file}")`, {
        weight: String(def.weight),
        style: def.style
      });
      document.fonts.add(face);
    } catch (err) {
      console.warn('[font-faces] 注册字体失败:', def, err);
    }
  });
})();

// 预加载某个字体族（返回 Promise，可忽略失败）
function preloadFontFamily(family) {
  if (document.fonts && document.fonts.load) {
    return document.fonts.load(`16px '${family}'`).catch(function () {});
  }
  return Promise.resolve();
}

function removeSegment(i) {
  const parts = splitText(state.text);
  if (parts.length <= 1) return;
  pushHistory();
  parts.splice(i, 1);
  state.text = parts.join('||');
  el.textInput.value = state.text;
  state.active = clamp(state.active, 0, parts.length - 1);
  syncControls();
  renderAll(true);
}

